#include <stdio.h>

int main(void)
{
int n;
 
    while (1) 
    {
        printf("请输入 1 到 100 之间的整数：");
 
        /* ① 检查返回值 */
        if (scanf("%d", &n) != 1) 
        {
            printf("  这不是一个整数，请重新输入。\n");
            /* ② 清空这一行的残留字符 —— 少了这两行就会死循环 */
            while (getchar() != '\n')
                continue;
            continue;
        }
 
        /* ③ 检查取值范围 */
        if (n < 1 || n > 100) 
        {
            printf("  超出范围了（你输入的是 %d），请重新输入。\n", n);
            continue;
        }
 
        break;                            /* 三重检查都过了，才跳出 */
    }
 
    printf("输入合法：%d\n", n);
    return 0;
}
